/* 
This is program explains an example of if-else if-else statement
*/

let myNumber = 0;

// Checking if the value is positive
if(myNumber > 0){
    console.log(`Positive Value -> ${myNumber}`);
}
else if (myNumber < 0){
    console.log(`Negative Value -> ${myNumber}`);
}
else{
    console.log(`Zero value -> ${myNumber} `);
}
