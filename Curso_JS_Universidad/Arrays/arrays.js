// Declaring array
let arrayNumber = [];

// Modifying values
arrayNumber[0] = 13;
arrayNumber[1] = 12;
arrayNumber[2] = 11;
arrayNumber[3] = 10;
arrayNumber[4] = 'hola';

// Printing array values
console.log(arrayNumber);

console.log(`Element 1 - [0]: ${arrayNumber[0]}`);
console.log(`Element 2 - [1]: ${arrayNumber[1]}`);
console.log(`Element 3 - [2]: ${arrayNumber[2]}`);
console.log(`Element 4 - [3]: ${arrayNumber[3]}`);
console.log(`Element 5 - [4]: ${arrayNumber[4]}`);