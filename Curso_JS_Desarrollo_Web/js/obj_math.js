// Objeto Math

let resultado;

resultado = Math.PI;
resultado = Math.round(2.5); // Redondea de .5 hacia arriba
console.log(resultado);

resultado = Math.ceil(2.1);  // Siempre redondea hacia arriba
console.log(resultado);

resultado = Math.floor(2.9);  // Siempre redondea hacia abajo
console.log(resultado);

resultado = Math.sqrt(144);  // Raiz cuadrada
console.log(resultado);

resultado = Math.abs(-2);  // Un número negativo lo convierte a positivo
console.log(resultado);

resultado = Math.min(2,5,78,1, 4, 6);  // Aquí nos indica cual es el número más pequeño de un listado
console.log(resultado);

resultado = Math.max(2,5,78,1, 4, 6);  // Aquí nos indica cual es el número más grande de un listado
console.log(resultado);

resultado = Math.random();  // Nos muestra un número aleatorio menos de 1
console.log(resultado);

resultado = Math.floor( Math.random() * 100 );  // Nos muestra un número aleatorio hasta el 100
console.log(resultado);

